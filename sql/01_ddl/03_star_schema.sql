-- 03_star_schema.sql   (run as AML_OWNER)
-- AML data warehouse: conformed dimensions, a monthly interval-partitioned
-- transaction fact, the alert fact produced by PKG_AML_RULES, and the case
-- table investigators work from.
-- ============================================================================

-- ---------------------------------------------------------------- dimensions
CREATE TABLE dim_date (
  date_key          NUMBER(8)     NOT NULL,
  cal_date          DATE          NOT NULL,
  day_of_week       VARCHAR2(9)   NOT NULL,
  day_of_month      NUMBER(2)     NOT NULL,
  month_num         NUMBER(2)     NOT NULL,
  month_name        VARCHAR2(9)   NOT NULL,
  quarter_num       NUMBER(1)     NOT NULL,
  year_num          NUMBER(4)     NOT NULL,
  is_weekend        CHAR(1)       NOT NULL,
  CONSTRAINT pk_dim_date PRIMARY KEY (date_key),
  CONSTRAINT uk_dim_date UNIQUE (cal_date)
);

CREATE TABLE dim_country (
  country_key       NUMBER GENERATED BY DEFAULT AS IDENTITY,
  country_code      VARCHAR2(5)   NOT NULL,
  risk_tier         VARCHAR2(20)  NOT NULL,
  is_high_risk      CHAR(1) GENERATED ALWAYS AS
                      (CASE WHEN risk_tier IN ('HIGH','PROHIBITED') THEN 'Y' ELSE 'N' END) VIRTUAL,
  updated_ts        TIMESTAMP     DEFAULT SYSTIMESTAMP,
  CONSTRAINT pk_dim_country PRIMARY KEY (country_key),
  CONSTRAINT uk_dim_country UNIQUE (country_code),
  CONSTRAINT ck_dim_country_tier CHECK (risk_tier IN ('LOW','MEDIUM','HIGH','PROHIBITED','UNKNOWN'))
);

-- Type 2 slowly changing dimension: KYC rating / PEP changes keep history,
-- so an alert can be explained with the customer profile as it was that day.
CREATE TABLE dim_customer (
  customer_key      NUMBER GENERATED BY DEFAULT AS IDENTITY,
  customer_id       VARCHAR2(20)  NOT NULL,
  customer_name     VARCHAR2(200) NOT NULL,
  customer_name_norm VARCHAR2(200),
  customer_type     VARCHAR2(20)  NOT NULL,
  date_of_birth     DATE,
  country_code      VARCHAR2(5),
  state_code        VARCHAR2(5),
  kyc_risk_rating   VARCHAR2(10)  NOT NULL,
  pep_flag          CHAR(1)       DEFAULT 'N' NOT NULL,
  onboard_date      DATE,
  row_hash          VARCHAR2(64)  NOT NULL,
  eff_start_date    DATE          NOT NULL,
  eff_end_date      DATE          DEFAULT DATE '9999-12-31' NOT NULL,
  is_current        CHAR(1)       DEFAULT 'Y' NOT NULL,
  batch_id          NUMBER,
  CONSTRAINT pk_dim_customer PRIMARY KEY (customer_key),
  CONSTRAINT ck_dim_customer_cur CHECK (is_current IN ('Y','N')),
  CONSTRAINT ck_dim_customer_kyc CHECK (kyc_risk_rating IN ('LOW','MEDIUM','HIGH'))
);

CREATE UNIQUE INDEX ux_dim_customer_current
  ON dim_customer (CASE WHEN is_current = 'Y' THEN customer_id END);
CREATE INDEX ix_dim_customer_id ON dim_customer (customer_id, eff_start_date);

CREATE TABLE dim_account (
  account_key       NUMBER GENERATED BY DEFAULT AS IDENTITY,
  account_id        VARCHAR2(20)  NOT NULL,
  customer_id       VARCHAR2(20)  NOT NULL,
  product_type      VARCHAR2(30)  NOT NULL,
  open_date         DATE,
  account_status    VARCHAR2(20)  NOT NULL,
  last_activity_date DATE,
  dormant_flag      CHAR(1)       DEFAULT 'N' NOT NULL,
  updated_ts        TIMESTAMP     DEFAULT SYSTIMESTAMP,
  batch_id          NUMBER,
  CONSTRAINT pk_dim_account PRIMARY KEY (account_key),
  CONSTRAINT uk_dim_account UNIQUE (account_id)
);

CREATE INDEX ix_dim_account_cust ON dim_account (customer_id);

CREATE TABLE dim_txn_type (
  txn_type_key      NUMBER        NOT NULL,
  txn_type_code     VARCHAR2(20)  NOT NULL,
  channel           VARCHAR2(20)  NOT NULL,
  direction         VARCHAR2(2)   NOT NULL,
  is_cash           CHAR(1)       NOT NULL,
  is_wire           CHAR(1)       NOT NULL,
  description       VARCHAR2(100),
  CONSTRAINT pk_dim_txn_type PRIMARY KEY (txn_type_key),
  CONSTRAINT uk_dim_txn_type UNIQUE (txn_type_code)
);

CREATE TABLE dim_sanctioned_party (
  sdn_key           NUMBER GENERATED BY DEFAULT AS IDENTITY,
  sdn_id            VARCHAR2(20)  NOT NULL,
  party_name        VARCHAR2(200) NOT NULL,
  party_name_norm   VARCHAR2(200) NOT NULL,
  party_type        VARCHAR2(20),
  country_code      VARCHAR2(5),
  list_source       VARCHAR2(40),
  active_flag       CHAR(1)       DEFAULT 'Y' NOT NULL,
  updated_ts        TIMESTAMP     DEFAULT SYSTIMESTAMP,
  CONSTRAINT pk_dim_sanctioned_party PRIMARY KEY (sdn_key),
  CONSTRAINT uk_dim_sanctioned_party UNIQUE (sdn_id)
);

-- --------------------------------------------------------- transaction fact
-- Interval partitioning by month: rule windows (5-30 days) prune to 1-2
-- partitions, and old months can be compressed or archived independently.
CREATE TABLE fact_transaction (
  txn_id              VARCHAR2(30)  NOT NULL,
  txn_ts              TIMESTAMP     NOT NULL,
  txn_date            DATE          NOT NULL,
  txn_date_key        NUMBER(8)     NOT NULL,
  account_key         NUMBER        NOT NULL,
  customer_key        NUMBER        NOT NULL,
  txn_type_key        NUMBER        NOT NULL,
  cp_country_key      NUMBER        NOT NULL,
  direction           VARCHAR2(2)   NOT NULL,
  amount              NUMBER(18,2)  NOT NULL,
  signed_amount       NUMBER(18,2)  NOT NULL,
  currency            VARCHAR2(3)   NOT NULL,
  counterparty_name   VARCHAR2(200),
  counterparty_name_norm VARCHAR2(200),
  batch_id            NUMBER        NOT NULL,
  load_ts             TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_fact_transaction PRIMARY KEY (txn_id),
  CONSTRAINT fk_fact_txn_acct    FOREIGN KEY (account_key)    REFERENCES dim_account (account_key),
  CONSTRAINT fk_fact_txn_cust    FOREIGN KEY (customer_key)   REFERENCES dim_customer (customer_key),
  CONSTRAINT fk_fact_txn_type    FOREIGN KEY (txn_type_key)   REFERENCES dim_txn_type (txn_type_key),
  CONSTRAINT fk_fact_txn_country FOREIGN KEY (cp_country_key) REFERENCES dim_country (country_key),
  CONSTRAINT ck_fact_txn_dir     CHECK (direction IN ('CR','DR')),
  CONSTRAINT ck_fact_txn_amt     CHECK (amount >= 0)
)
PARTITION BY RANGE (txn_date) INTERVAL (NUMTOYMINTERVAL(1,'MONTH'))
( PARTITION p_initial VALUES LESS THAN (DATE '2025-01-01') );

CREATE INDEX ix_fact_txn_acct_date ON fact_transaction (account_key, txn_date) LOCAL;
CREATE INDEX ix_fact_txn_type_date ON fact_transaction (txn_type_key, txn_date) LOCAL;
CREATE INDEX ix_fact_txn_batch     ON fact_transaction (batch_id) LOCAL;

-- Rows that fail constraints during the fact MERGE land here instead of
-- aborting the whole load (LOG ERRORS ... REJECT LIMIT UNLIMITED).
BEGIN
  DBMS_ERRLOG.CREATE_ERROR_LOG(dml_table_name     => 'FACT_TRANSACTION',
                               err_log_table_name => 'ERR$_FACT_TRANSACTION');
END;
/

-- ------------------------------------------------------------- rule config
CREATE TABLE aml_rule_config (
  rule_code          VARCHAR2(30)   NOT NULL,
  rule_name          VARCHAR2(100)  NOT NULL,
  description        VARCHAR2(1000),
  threshold_amount   NUMBER(18,2),
  lower_bound_amount NUMBER(18,2),
  lookback_days      NUMBER(3),
  min_txn_count      NUMBER(5),
  pct_threshold      NUMBER(5,2),
  match_score        NUMBER(3),
  inactivity_days    NUMBER(4),
  severity           VARCHAR2(10)   NOT NULL,
  base_risk_score    NUMBER(3)      NOT NULL,
  is_active          CHAR(1)        DEFAULT 'Y' NOT NULL,
  updated_by         VARCHAR2(60),
  updated_ts         TIMESTAMP,
  CONSTRAINT pk_aml_rule_config PRIMARY KEY (rule_code),
  CONSTRAINT ck_aml_rule_sev CHECK (severity IN ('LOW','MEDIUM','HIGH','CRITICAL')),
  CONSTRAINT ck_aml_rule_active CHECK (is_active IN ('Y','N'))
);

-- Every threshold change is kept: examiners ask "what was the rule on date X?"
CREATE TABLE aml_rule_config_hist (
  hist_id            NUMBER GENERATED ALWAYS AS IDENTITY,
  rule_code          VARCHAR2(30)   NOT NULL,
  change_type        VARCHAR2(10)   NOT NULL,
  old_values         VARCHAR2(4000),
  new_values         VARCHAR2(4000),
  changed_by         VARCHAR2(60)   NOT NULL,
  changed_ts         TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_aml_rule_config_hist PRIMARY KEY (hist_id)
);

-- ------------------------------------------------------------- case & alerts
CREATE TABLE aml_case (
  case_id            NUMBER GENERATED BY DEFAULT AS IDENTITY,
  customer_key       NUMBER         NOT NULL,
  customer_id        VARCHAR2(20)   NOT NULL,
  case_status        VARCHAR2(20)   DEFAULT 'OPEN' NOT NULL,
  priority           VARCHAR2(10)   NOT NULL,
  alert_count        NUMBER         DEFAULT 0 NOT NULL,
  max_risk_score     NUMBER(3)      DEFAULT 0 NOT NULL,
  assigned_to        VARCHAR2(60),
  opened_ts          TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  last_alert_ts      TIMESTAMP,
  closed_ts          TIMESTAMP,
  disposition        VARCHAR2(30),
  CONSTRAINT pk_aml_case PRIMARY KEY (case_id),
  CONSTRAINT ck_aml_case_status CHECK (case_status IN ('OPEN','IN_REVIEW','ESCALATED','SAR_FILED','CLOSED')),
  CONSTRAINT ck_aml_case_prio   CHECK (priority IN ('LOW','MEDIUM','HIGH','CRITICAL'))
);

-- One open case per customer: new alerts attach to it (see trg_alert_case)
CREATE UNIQUE INDEX ux_aml_case_open
  ON aml_case (CASE WHEN case_status <> 'CLOSED' THEN customer_id END);

CREATE TABLE fact_aml_alert (
  alert_id           NUMBER GENERATED BY DEFAULT AS IDENTITY,
  rule_code          VARCHAR2(30)   NOT NULL,
  account_key        NUMBER         NOT NULL,
  customer_key       NUMBER         NOT NULL,
  alert_date_key     NUMBER(8)      NOT NULL,
  window_start_date  DATE           NOT NULL,
  window_end_date    DATE           NOT NULL,
  txn_count          NUMBER         NOT NULL,
  total_amount       NUMBER(18,2)   NOT NULL,
  risk_score         NUMBER(3)      NOT NULL,
  severity           VARCHAR2(10)   NOT NULL,
  alert_status       VARCHAR2(20)   DEFAULT 'NEW' NOT NULL,
  alert_reason       VARCHAR2(1000) NOT NULL,
  match_detail       VARCHAR2(400),
  case_id            NUMBER,
  batch_id           NUMBER         NOT NULL,
  created_ts         TIMESTAMP,
  created_by         VARCHAR2(60),
  updated_ts         TIMESTAMP,
  updated_by         VARCHAR2(60),
  CONSTRAINT pk_fact_aml_alert PRIMARY KEY (alert_id),
  -- Natural key = idempotency: rerunning a batch cannot double-alert
  CONSTRAINT uk_fact_aml_alert UNIQUE (rule_code, account_key, window_start_date),
  CONSTRAINT fk_alert_rule  FOREIGN KEY (rule_code)   REFERENCES aml_rule_config (rule_code),
  CONSTRAINT fk_alert_acct  FOREIGN KEY (account_key) REFERENCES dim_account (account_key),
  CONSTRAINT fk_alert_cust  FOREIGN KEY (customer_key) REFERENCES dim_customer (customer_key),
  CONSTRAINT fk_alert_case  FOREIGN KEY (case_id)     REFERENCES aml_case (case_id),
  CONSTRAINT ck_alert_status CHECK (alert_status IN ('NEW','IN_REVIEW','ESCALATED','CLOSED_FP','CLOSED_SAR')),
  CONSTRAINT ck_alert_score  CHECK (risk_score BETWEEN 0 AND 100)
);

CREATE INDEX ix_alert_case   ON fact_aml_alert (case_id);
CREATE INDEX ix_alert_date   ON fact_aml_alert (alert_date_key, rule_code);
CREATE INDEX ix_alert_batch  ON fact_aml_alert (batch_id);

-- Bridge: which transactions triggered which alert (evidence trail)
CREATE TABLE fact_alert_txn (
  alert_id           NUMBER         NOT NULL,
  txn_id             VARCHAR2(30)   NOT NULL,
  CONSTRAINT pk_fact_alert_txn PRIMARY KEY (alert_id, txn_id),
  CONSTRAINT fk_alert_txn_alert FOREIGN KEY (alert_id) REFERENCES fact_aml_alert (alert_id),
  CONSTRAINT fk_alert_txn_txn   FOREIGN KEY (txn_id)   REFERENCES fact_transaction (txn_id)
);

CREATE INDEX ix_alert_txn_txn ON fact_alert_txn (txn_id);

-- Immutable audit of alert status changes
CREATE TABLE aml_alert_audit (
  audit_id           NUMBER GENERATED ALWAYS AS IDENTITY,
  alert_id           NUMBER         NOT NULL,
  old_status         VARCHAR2(20),
  new_status         VARCHAR2(20),
  changed_by         VARCHAR2(60)   NOT NULL,
  changed_ts         TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_aml_alert_audit PRIMARY KEY (audit_id)
);
